"""Deterministic object-store "volume" layout for the Flyte backend.

Modal backed shared, persistent state with ``modal.Volume``s at fixed mount
paths. Flyte 2 persists task I/O in its object store (the cluster's backing
store — MinIO on the devbox, S3/GCS/R2 on Union) and syncs it into each task
container as a local path via ``flyte.io.Dir`` / ``flyte.io.File``.

We model each Modal volume as a **deterministic object-key prefix** so that:

- the Hugging Face cache is shared per model across runs (read-mostly),
- training data and checkpoints are run-scoped and persist across runs.

``training_run_id`` is generated by ``TrainConfig._generate_training_run_id()``
so linkage to ``TrainingRun`` records and the dashboard survives the port.
"""

from __future__ import annotations

from pathlib import PurePosixPath


def hf_cache_prefix(model_name: str | None) -> str:
    """Object-key prefix for a model's shared HF cache ("volume")."""
    if not model_name:
        model_name = "unknown-model"
    return f"dojo/models/{model_name}/hf-cache"


def data_prefix(run_id: str) -> str:
    """Object-key prefix for the run's materialized training data."""
    return f"dojo/runs/{run_id}/data"


def checkpoints_prefix(run_id: str) -> str:
    """Object-key prefix for the run's training outputs (checkpoints)."""
    return f"dojo/runs/{run_id}/checkpoints"


def join(*parts: str) -> str:
    """Join object-key parts with forward slashes, tolerating ``/`` in names."""
    return str(PurePosixPath(*[p.strip("/") for p in parts]))


def dataset_jsonl_path(prefix: str, index: int = 0) -> str:
    """Local/object path where the materialized dataset JSONL is written."""
    return join(prefix, f"data-{index}.jsonl")


def cache_hit_marker(prefix: str) -> str:
    """Path of a marker file that records cache validity for a prefix."""
    return join(prefix, ".dojo-cache-ok")
