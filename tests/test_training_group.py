def test_training_run_persists_group_id(fake_volume):
    from modal_dojo.common.framework import Framework

    run = TrainingRun(
        training_run_id="run-x",
        framework=Framework.SLIME,
        config={},
        metadata={"group_id": "group-abc123"},
    )
    run.save()
    restored = TrainingRun.from_id("run-x")
    assert restored.group_id == "group-abc123"


def test_training_run_result_returns_self(fake_volume):
    from modal_dojo.common.framework import Framework

    class FakeFunctionCall:
        def get(self, timeout=None):
            assert timeout == 123
            return {
                "app_name": "run-x",
                "metrics": {"score": 1},
            }

    run = TrainingRun(
        training_run_id="run-x",
        modal_app_id="",
        modal_app_url="",
        framework=Framework.SLIME,
        config={},
        function_call_id="fc-123",
        metadata={"group_id": "group-abc123"},
    )
    run._function_call = FakeFunctionCall()

    assert run.group_id == "group-abc123"

    result = run.result(timeout=123, stop_app_on_success=False)
    assert result is run
    assert result.training_run_id == "run-x"
    assert result.group_id == "group-abc123"
    assert result.app_name == "run-x"
    assert result.metrics == {"score": 1}


def test_iter_variants_pairs_overrides_with_configs():
    group = TrainingGroup(base=_base(), grid={"recipe.lr": [1e-6, 5e-6]})
    variants = group.iter_variants()
    assert [ov for ov, _ in variants] == [
        {"recipe.lr": 1e-6},
        {"recipe.lr": 5e-6},
    ]
    assert all(cfg.recipe.lr == ov["recipe.lr"] for ov, cfg in variants)


def test_variant_plan_prints_overrides(capsys):
    group = TrainingGroup(base=_base(), grid={"recipe.lr": [1e-6, 5e-6]})
    variants = group.iter_variants()

    group._print_variant_plan(variants)

    output = capsys.readouterr().out
    for overrides, cfg in variants:
        assert repr(overrides) in output
        context_plan_line = cfg.context_plan_line()
        assert context_plan_line is not None
        assert context_plan_line in output


def test_group_variants_record_tag_metadata():
    group = TrainingGroup(
        base=_base(),
        name="Batch Sweep",
        grid={
            "recipe.rollout_batch_size": [16],
            "recipe.lr": [1e-6],
        },
    )
    overrides, cfg = group.iter_variants()[0]

    assert overrides == {
        "recipe.rollout_batch_size": 16,
        "recipe.lr": 1e-6,
    }
    assert cfg.group_id == "batch-sweep"
    assert cfg.group_overrides == overrides
    assert cfg.group_axes == ["recipe.rollout_batch_size", "recipe.lr"]

    metadata = cfg._build_run_metadata()
    assert metadata == {
        "group_id": "batch-sweep",
        "group_tags": {
            "group_id": "batch-sweep",
            "axes": ["recipe.rollout_batch_size", "recipe.lr"],
            "overrides": {
                "recipe.rollout_batch_size": 16,
                "recipe.lr": 1e-6,
            },
            "tags": [
                {
                    "key": "recipe.rollout_batch_size",
                    "label": "rollout batch size",
                    "value": 16,
                },
                {"key": "recipe.lr", "label": "lr", "value": 1e-6},
            ],
        },
    }


def test_skip_invalid_drops_failing_points_and_records_reason(capsys):
    base = _base()
    base.recipe.actor_num_gpus_per_node = 8
    base.recipe.rollout_num_gpus = 8
    group = TrainingGroup(
        base=base,
        grid={"recipe.expert_model_parallel_size": [1, 3, 8]},
        skip_invalid=True,
    )
    assert [o for o, _ in group.iter_variants()] == [
        {"recipe.expert_model_parallel_size": 1},
        {"recipe.expert_model_parallel_size": 8},
    ]
    [(overrides, reason)] = group.skipped
    assert overrides == {"recipe.expert_model_parallel_size": 3}
    assert "not divisible" in reason
    assert "validation error" not in reason
    assert (
        "skipping {'recipe.expert_model_parallel_size': 3}" in capsys.readouterr().out
    )


def test_invalid_points_still_raise_by_default():
    base = _base()
    base.recipe.actor_num_gpus_per_node = 8
    base.recipe.rollout_num_gpus = 8
    group = TrainingGroup(base=base, grid={"recipe.expert_model_parallel_size": [3]})
    with pytest.raises(TrainingGroupError, match="not divisible"):
        group.iter_variants()
    assert group.skipped == []


def test_skip_invalid_applies_model_parallelism_preflight():
    base = _base()
    base.recipe.actor_num_gpus_per_node = 8
    base.recipe.rollout_num_gpus = 8
    base.model.architecture.num_experts = 12
    group = TrainingGroup(
        base=base,
        grid={"recipe.expert_model_parallel_size": [4, 8]},
        skip_invalid=True,
    )
    assert [o for o, _ in group.iter_variants()] == [
        {"recipe.expert_model_parallel_size": 4}
    ]
    [(_, reason)] = group.skipped
    assert "12" in reason and "8" in reason
